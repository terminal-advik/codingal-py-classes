# Data-Types

# Examples of different data types in Python
integer_example = 10
float_example = 10.5
string_example = "Hello, World! \nI'm in Grade 6 and my age is 11."
boolean_example = True

print("Integer:", integer_example)
print("Float:", float_example)
print("String:", string_example)
print("Boolean:", boolean_example)

# limit of different data types in Python
import sys
print("Maximum size of an integer:", sys.maxsize)
print("Maximum size of a float:", sys.float_info.max)
print("Maximum size of a string:", sys.maxsize)

# other data types
list_example = [1, 2, 3, 4, 5] # list is mutable
tuple_example = (1, 2, 3, 4, 5) # tuple is immutable
set_example = {1, 2, 3, 4, 5} # set is mutable and unordered. set items are unique.
dict_example = {"name": "Alice", "age": 11} # dictionary is mutable and stores key-value pairs

print("List:", list_example)
print("Tuple:", tuple_example)
print("Set:", set_example)
print("Dictionary:", dict_example)


